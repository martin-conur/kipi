//! `generated/registry.<scope>.md`: one line per repo in a scope's registry
//! (roadmap §2, §8 step 2).

use std::path::{Path, PathBuf};

use serde::Serialize;

use super::LineView;
use crate::plan::Registry;

/// The store directory holding generated registries (gitignored by the store).
pub const GENERATED_DIR: &str = "generated";

/// `generated/registry.<scope>.md`, relative to the owning store.
pub fn relative_path(scope: &str) -> PathBuf {
    Path::new(GENERATED_DIR).join(format!("registry.{scope}.md"))
}

/// A registry as the templates see it.
#[derive(Debug, Serialize)]
pub(super) struct RegistryView<'a> {
    store: &'a str,
    scope: &'a str,
    entries: Vec<LineView<'a>>,
}

impl<'a> RegistryView<'a> {
    pub(super) fn new(registry: &'a Registry, home: Option<&Path>) -> Self {
        RegistryView {
            store: &registry.store,
            scope: &registry.scope,
            entries: registry
                .entries
                .iter()
                .map(|e| LineView::entry(e, home))
                .collect(),
        }
    }
}

/// The registry file for `registry`: a header and one line per entry, in the
/// registry's (name) order. `home` is shown as `~`.
pub fn render(registry: &Registry, home: Option<&Path>) -> String {
    super::render("registry.md.j2", RegistryView::new(registry, home))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::plan::{RegistryEntry, Source};

    fn entry(name: &str) -> RegistryEntry {
        RegistryEntry {
            name: name.to_owned(),
            aliases: Vec::new(),
            aliases_draft: false,
            summary: None,
            summary_draft: false,
            scope: "s".to_owned(),
            local: None,
            notes: None,
            keys: vec![name.to_owned()],
            source: Source::builtin("test"),
        }
    }

    fn registry(entries: Vec<RegistryEntry>) -> Registry {
        Registry {
            scope: "s".to_owned(),
            store: "st".to_owned(),
            scopes: vec!["s".to_owned()],
            entries,
            collisions: Vec::new(),
            source: Source::builtin("test"),
        }
    }

    #[test]
    fn path_is_per_scope_under_generated() {
        assert_eq!(
            relative_path("acme-ml"),
            PathBuf::from("generated/registry.acme-ml.md")
        );
    }

    #[test]
    fn line_shapes() {
        let home = Path::new("/h");
        let full = RegistryEntry {
            aliases: vec!["a".into(), "b c".into()],
            summary: Some("Does things".into()),
            local: Some("/h/code/full".into()),
            notes: Some("/h/store/repos/full/notes.md".into()),
            ..entry("full")
        };
        let bare = entry("bare");
        let elsewhere = RegistryEntry {
            summary: Some("Elsewhere".into()),
            local: Some("/srv/x".into()),
            ..entry("elsewhere")
        };
        let text = render(&registry(vec![bare, elsewhere, full]), Some(home));
        assert_eq!(
            text,
            "<!-- generated by kipi from st:bindings.toml (do not edit; regenerate with `kipi sync`) -->\n\
             # Known repos (s)\n\
             \n\
             - bare · (not cloned here)\n\
             - elsewhere — Elsewhere · /srv/x\n\
             - full (a, b c) — Does things · ~/code/full · notes: ~/store/repos/full/notes.md\n"
        );
    }

    #[test]
    fn empty_registry_has_header_only() {
        assert_eq!(
            render(&registry(Vec::new()), None),
            "<!-- generated by kipi from st:bindings.toml (do not edit; regenerate with `kipi sync`) -->\n\
             # Known repos (s)\n\n"
        );
    }
}
